import type { Expression } from "../types";

// Original teaching notes and examples. These are language building blocks, not essay templates.
type Row = [
  english: string,
  chinese: string,
  topic: string,
  category: string,
  usage: string,
  example?: string,
];
function makeExpressions(prefix: string, rows: Row[]): Expression[] {
  return rows.map(
    ([english, chinese, topic, category, usage, example], index) => ({
      id: `${prefix}-${String(index + 1).padStart(3, "0")}`,
      english,
      chinese,
      topic,
      category,
      usage,
      ...(example ? { example } : {}),
      sourceType: "本站原创整理（通用表达，非官方答案）",
      keywords: [topic, category],
    }),
  );
}

